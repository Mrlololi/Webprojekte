  /**
   * The phrase card sits far down the page and laying out its 45 rows is the
   * heaviest work of the page: draw it when it comes within about a screen,
   * or right before printing, not while the page loads.
   */
  var sheetState = { dirty: false, near: false, observer: null };

  function scheduleSheet() {
    sheetState.dirty = true;
    if (sheetState.near || !('IntersectionObserver' in window)) {
      flushSheet();
      return;
    }
    if (!sheetState.observer) {
      sheetState.observer = new IntersectionObserver(function (entries) {
        sheetState.near = entries.some(function (e) { return e.isIntersecting; });
        if (sheetState.near) flushSheet();
      }, { rootMargin: '800px 0px' });
      sheetState.observer.observe(el.sheet);
    }
  }

  function flushSheet() {
    if (!sheetState.dirty) return;
    sheetState.dirty = false;
    renderSheet();
  }

  /**
   * The sheet has the A4 ratio and all its sizes are in container units, so
   * what fits on screen fits on paper. Shrink the type until it fits.
   */
  function fitSheet() {
    var sheet = el.sheet;
    var inner = sheet.firstElementChild;
    if (!inner || !sheet.offsetWidth) return;
    var limit = function () {
      var style = window.getComputedStyle(sheet);
      return sheet.clientHeight - parseFloat(style.paddingTop) - parseFloat(style.paddingBottom);
    };
    var fits = function (value) {
      sheet.style.setProperty('--fit', value.toFixed(3));
      return inner.scrollHeight <= limit() * 0.985;
    };
    // Steps of 0.025 from 1 down to 0.55; the largest one that fits wins. A binary search
    // needs about 5 layouts instead of up to 19 (each one lays out all 45 phrases).
    var steps = [];
    for (var i = 0; i <= 18; i++) steps.push(1 - i * 0.025);
    var scale = steps[steps.length - 1];
    if (fits(steps[0])) {
      scale = steps[0];
    } else {
      var lo = 1;
      var hi = steps.length - 1;
      while (lo < hi) {
        var mid = (lo + hi) >> 1;
        if (fits(steps[mid])) hi = mid; else lo = mid + 1;
      }
      scale = steps[lo];
    }
    sheet.style.setProperty('--fit', scale.toFixed(3));
    sheet.setAttribute('data-fit', scale.toFixed(3));
  }

