  /* Review mode: ?review (language picker) and ?review=fi               */
  /* For native speakers who open one link from a group chat, usually on */
  /* a phone. They mark each phrase "Correct" or suggest a fix; the      */
  /* marks stay in localStorage per language. Nothing is ever sent: they */
  /* copy, share or e-mail the text themselves.                          */
  /* ------------------------------------------------------------------ */

  var review = { code: '', marks: {}, fixes: {} };

  function reviewUi() {
    var fromUrl = params().get('ui');
    if (fromUrl === 'de' || fromUrl === 'en') return fromUrl;
    var saved = store.get('ui', null);
    if (saved === 'de' || saved === 'en') return saved;
    return String(navigator.language || 'en').toLowerCase().split('-')[0] === 'de' ? 'de' : 'en';
  }

  function reviewHref(code, ui) {
    return '?review' + (code ? '=' + code : '') + '&ui=' + (ui || state.ui);
  }

  /** EN / DE links at the top of the review page (it has no app header). */
  function reviewLangLinks() {
    var nav = make('ul', 'review__langs');
    nav.setAttribute('aria-label', 'Language / Sprache');
    [['en', 'EN', 'English'], ['de', 'DE', 'Deutsch']].forEach(function (l) {
      var li = document.createElement('li');
      var a = make('a', '', l[1]);
      a.href = reviewHref(review.code, l[0]);
      a.lang = l[0];
      a.appendChild(span('visually-hidden', ' ' + l[2]));
      if (l[0] === state.ui) a.setAttribute('aria-current', 'true');
      li.appendChild(a);
      nav.appendChild(li);
    });
    return nav;
  }

  function reviewHead(titleText, introText) {
    var head = make('div', 'review__head');
    head.append(reviewLangLinks(), make('h1', 'review__title', titleText), make('p', 'review__intro', introText));
    return head;
  }

  /** All 42 languages: drafts first, each part sorted by name in the UI language. */
  function renderReviewPicker(note) {
    document.title = 'Language Starter: ' + t('review.pickTitle');
    var codes = sortedCodes();
    var drafts = codes.filter(function (c) { return !state.checkedLang[c]; });
    var done = codes.filter(function (c) { return state.checkedLang[c]; });
    var list = make('ul', 'review-pick');
    list.setAttribute('aria-label', t('review.pickList'));
    drafts.concat(done).forEach(function (code) {
      var li = document.createElement('li');
      var a = make('a', 'review-pick__item');
      a.href = reviewHref(code);
      a.append(
        span('review-pick__endonym', langData(code).endonym, code),
        span('review-pick__name', langName(code) + ' (' + code + ')'),
        span('pick__badge' + (state.checkedLang[code] ? ' is-checked' : ''), t(state.checkedLang[code] ? 'chooser.checked' : 'chooser.draft'))
      );
      li.appendChild(a);
      list.appendChild(li);
    });
    var parts = [reviewHead(t('review.pickTitle'), t('review.pickIntro'))];
    if (note) parts.push(make('p', 'review__error', note));
    parts.push(list);
    el.review.replaceChildren.apply(el.review, parts);
  }

  function reviewKey() { return 'review:' + review.code; }

  function saveReview() {
    store.set(reviewKey(), { marks: review.marks, fixes: review.fixes });
  }

  function reviewStats() {
    var numbers = state.order.map(function (id) { return entry('en', id).n; });
    var marked = numbers.filter(function (n) { return review.marks[n]; });
    var fixes = numbers.filter(function (n) { return review.marks[n] === 'fix' && String(review.fixes[n] || '').trim(); });
    return { numbers: numbers, marked: marked, fixes: fixes };
  }

  /** The plain text people paste into the group chat. Honest about what was not looked at:
      phrases after the last one they marked count as "Not checked". */
  function reviewText() {
    var info = langData(review.code);
    var s = reviewStats();
    var lines = ['Language Starter · ' + info.endonym + ' (' + review.code + ')'];
    s.fixes.forEach(function (n) { lines.push(n + ': ' + String(review.fixes[n]).trim().replace(/\s*\n\s*/g, ' / ')); });
    var last = s.marked.length ? Math.max.apply(null, s.marked) : 0;
    var max = Math.max.apply(null, s.numbers);
    var range = function (from) { return from === max ? String(max) : from + '-' + max; };
    var others = s.fixes.length ? 'All other phrases' : 'All phrases';
    if (last === max) lines.push(others + ' look correct.');
    else if (last > 0) lines.push(others + ' up to ' + last + ' look correct.', 'Not checked: ' + range(last + 1));
    else lines.push('Not checked: ' + range(1));
    return lines.join('\n');
  }

  function mailHref() {
    return 'mailto:' + MAIL + '?subject=' + encodeURIComponent('Language Starter: ' + review.code) + '&body=' + encodeURIComponent(reviewText());
  }

  var reviewEl = {};

  function updateReviewBar() {
    var s = reviewStats();
    reviewEl.count.textContent = t('review.count', { n: s.fixes.length }) + ' · ' + t('review.progress', { done: s.marked.length, total: s.numbers.length });
    reviewEl.mail.href = mailHref();
    if (!reviewEl.manual.hidden) reviewEl.manualText.value = reviewText();
  }

  function announce(text) {
    reviewEl.live.textContent = '';
    window.setTimeout(function () { reviewEl.live.textContent = text; }, 50);
  }

  /** WhatsApp, Instagram and Facebook open links in their own browser, where the clipboard
      API often fails: then the text appears selected in a box to long-press. */
  function showManualCopy() {
    reviewEl.manual.hidden = false;
    reviewEl.manualText.value = reviewText();
    reviewEl.manualText.focus();
    reviewEl.manualText.select();
    announce(t('review.copyManual'));
  }

  function copyReview() {
    var text = reviewText();
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(function () {
        reviewEl.manual.hidden = true;
        announce(t('review.copied'));
      }, showManualCopy);
    } else {
      showManualCopy();
    }
  }

  function shareReview() {
    navigator.share({ title: 'Language Starter: ' + review.code, text: reviewText() }).catch(function () { /* cancelled */ });
  }

  function setMark(n, mark, row) {
    review.marks[n] = review.marks[n] === mark && mark === 'ok' ? '' : mark;
    if (!review.marks[n]) delete review.marks[n];
    saveReview();
    paintRow(row, n);
    updateReviewBar();
    if (mark === 'fix' && review.marks[n] === 'fix') row.querySelector('textarea').focus();
  }

  function paintRow(row, n) {
    var mark = review.marks[n] || '';
    row.setAttribute('data-mark', mark);
    row.querySelector('[data-mark="ok"]').setAttribute('aria-pressed', String(mark === 'ok'));
    row.querySelector('[data-mark="fix"]').setAttribute('aria-pressed', String(mark === 'fix'));
    row.querySelector('.rv-fix').hidden = mark !== 'fix';
  }

  function both(e, field) {
    var v = e[field];
    if (!v) return '';
    return typeof v === 'object' ? 'm: ' + plain(v.m) + ' / f: ' + plain(v.f) : plain(v);
  }

  function renderReview(code) {
    var info = langData(code);
    review.code = code;
    var saved = store.get(reviewKey(), null) || {};
    review.marks = saved.marks && typeof saved.marks === 'object' ? saved.marks : {};
    review.fixes = saved.fixes && typeof saved.fixes === 'object' ? saved.fixes : {};

    var label = info.endonym + ' (' + code + ')';
    document.title = 'Language Starter: ' + t('review.title', { lang: label });
    var head = reviewHead('', t('review.intro'));
    var title = head.querySelector('h1');
    title.append(document.createTextNode(t('review.title', { lang: '' }).replace(/\s*$/, ' ')), span('', info.endonym, code), document.createTextNode(' (' + code + ')'));

    var actions = make('p', 'review__actions');
    var back = make('a', 'btn btn--quiet', t('review.all'));
    back.href = reviewHref('');
    var print = make('button', 'btn btn--outline review__print', t('review.print'));
    print.type = 'button';
    print.addEventListener('click', function () { window.print(); });
    actions.append(back, print);

    var hasTranslit = state.order.some(function (id) { return Boolean(entry(code, id).translit); });
    var table = make('table', 'review__table');
    var thead = document.createElement('thead');
    var headRow = document.createElement('tr');
    ['review.colN', 'review.colEn', 'review.colMeaning', 'review.colText'].concat(hasTranslit ? ['review.colLatin'] : []).concat(['review.colCheck']).forEach(function (key) {
      var th = make('th', key === 'review.colCheck' ? 'rv-check-head' : '', key === 'review.colText' ? t(key) + ': ' + info.endonym : t(key));
      th.scope = 'col';
      headRow.appendChild(th);
    });
    thead.appendChild(headRow);
    var tbody = document.createElement('tbody');
    state.order.forEach(function (id) {
      var e = entry(code, id);
      var base = entry('en', id) || {};
      var n = e.n;
      var tr = make('tr', 'rv-row');
      tr.id = 'p' + n;
      var num = make('th', 'review__n', String(n));
      num.scope = 'row';
      var english = make('td', 'rv-en', plain(base.text || ''));
      english.lang = 'en';
      var meaning = make('td', 'review__meaning', plain(base.meaning || ''));
      meaning.lang = 'en';
      var translation = make('td', 'rv-text', e.forms ? 'm: ' + plain(e.forms.m) + ' / f: ' + plain(e.forms.f) : plain(e.text));
      translation.lang = code;
      tr.append(num, english, meaning, translation);
      if (hasTranslit) {
        var latin = make('td', 'rv-latin', both(e, 'translit'));
        latin.lang = code + '-Latn';
        tr.appendChild(latin);
      }
      var check = make('td', 'rv-check');
      var buttons = make('div', 'rv-buttons');
      [['ok', 'review.ok'], ['fix', 'review.fix']].forEach(function (b) {
        var button = make('button', 'rv-btn rv-btn--' + b[0], t(b[1]));
        button.type = 'button';
        button.setAttribute('data-mark', b[0]);
        button.setAttribute('aria-pressed', 'false');
        button.setAttribute('aria-describedby', 'p' + n + '-n');
        buttons.appendChild(button);
      });
      num.id = 'p' + n + '-n';
      var fix = make('div', 'rv-fix');
      var fieldId = 'fix-' + n;
      var fixLabel = make('label', 'rv-fix__label', t('review.fixLabel', { n: n }));
      fixLabel.htmlFor = fieldId;
      var area = document.createElement('textarea');
      area.id = fieldId;
      area.className = 'rv-fix__field';
      area.rows = 2;
      area.lang = code;
      area.value = review.fixes[n] || '';
      area.addEventListener('input', function () {
        review.fixes[n] = area.value;
        saveReview();
        updateReviewBar();
      });
      fix.append(fixLabel, area);
      check.append(buttons, fix);
      tr.appendChild(check);
      buttons.addEventListener('click', function (event) {
        var button = event.target.closest('[data-mark]');
        if (button) setMark(n, button.getAttribute('data-mark'), tr);
      });
      tbody.appendChild(tr);
      paintRow(tr, n);
    });
    table.append(thead, tbody);

    // The sticky bar: count, copy, share, e-mail, and the hint where to paste it.
    var bar = make('div', 'rv-bar');
    bar.setAttribute('role', 'region');
    bar.setAttribute('aria-label', t('review.colCheck'));
    var count = make('p', 'rv-bar__count');
    var tools = make('div', 'rv-bar__tools');
    var copy = make('button', 'btn btn--primary rv-bar__copy', t('review.copy'));
    copy.type = 'button';
    copy.addEventListener('click', copyReview);
    tools.appendChild(copy);
    if (navigator.share) {
      var share = make('button', 'btn btn--outline', t('review.share'));
      share.type = 'button';
      share.addEventListener('click', shareReview);
      tools.appendChild(share);
    }
    var mail = make('a', 'btn btn--outline', t('review.mail'));
    tools.appendChild(mail);
    var hint = make('p', 'rv-bar__hint', t('review.hint'));
    var manual = make('div', 'rv-bar__manual');
    manual.hidden = true;
    var manualLabel = make('label', 'rv-fix__label', t('review.manualLabel'));
    manualLabel.htmlFor = 'rv-manual';
    var manualText = document.createElement('textarea');
    manualText.id = 'rv-manual';
    manualText.className = 'rv-fix__field';
    manualText.readOnly = true;
    manualText.rows = 5;
    manual.append(manualLabel, manualText, make('p', 'rv-bar__hint', t('review.copyManual')));
    var live = make('p', 'visually-hidden');
    live.setAttribute('aria-live', 'polite');
    bar.append(count, tools, hint, manual, live);
    reviewEl = { count: count, mail: mail, manual: manual, manualText: manualText, live: live };

    el.review.replaceChildren(head, actions, make('p', 'review__stored', t('review.stored')), table, bar);
    updateReviewBar();
    // Room for the fixed bar below the last phrase and above a focused field.
    var barHeight = function () { document.documentElement.style.setProperty('--rv-bar-h', bar.offsetHeight + 'px'); };
    barHeight();
    if ('ResizeObserver' in window) new ResizeObserver(barHeight).observe(bar);
  }

  function bootReview(code) {
    var root = document.documentElement;
    root.classList.add('is-review');
    root.classList.remove('i18n-pending');
    var robots = document.createElement('meta');
    robots.name = 'robots';
    robots.content = 'noindex, nofollow';
    document.head.appendChild(robots);
    state.ui = reviewUi();
    root.lang = state.ui;
    el.review.hidden = false;
    loadIndex()
      .then(function () {
        if (!code) return renderReviewPicker();
        if (!state.data.languages[code]) {
          review.code = '';
          return renderReviewPicker(t('review.unknown', { code: code }));
        }
        return loadLangs([code, 'en']).then(function () { renderReview(code); });
      })
      .catch(function () {
        el.review.textContent = t('review.loadError');
      });
  }

