  function loadScriptFallback() {
    return new Promise(function (resolve, reject) {
      if (window.LS_PHRASES) {
        resolve(window.LS_PHRASES);
        return;
      }
      var script = document.createElement('script');
      script.src = DATA_FALLBACK_URL;
      script.onload = function () {
        if (window.LS_PHRASES) resolve(window.LS_PHRASES);
        else reject(new Error('phrases.js did not define LS_PHRASES'));
      };
      script.onerror = function () { reject(new Error('phrases.js failed to load')); };
      document.head.appendChild(script);
    });
  }

  function fetchJson(url) {
    return fetch(url).then(function (response) {
      if (!response.ok) throw new Error('HTTP ' + response.status);
      return response.json();
    });
  }

  /** Languages, groups and phrase order (data/index.json, or built from the full data). */
  function indexMeta(index) {
    if (!index || !index.languages || !Array.isArray(index.phrases) || !Array.isArray(index.groups)) {
      throw new Error('Invalid phrases data');
    }
    state.data = index;
    state.codes = Object.keys(index.languages);
    state.order = index.phrases.slice().sort(function (x, y) { return x.n - y.n; }).map(function (p) {
      state.groupOf[p.id] = p.group;
      return p.id;
    });
    state.codes.forEach(function (code) { state.checkedLang[code] = index.languages[code].checked === true; });
  }

  function addEntries(list) {
    list.forEach(function (e) {
      (state.byLang[e.lang] = state.byLang[e.lang] || {})[e.id] = e;
      state.loaded[e.lang] = true;
    });
  }

  /** phrases.js (file://) or a failed split file: everything from the one big copy. */
  function useFull(data) {
    if (!data || !data.languages || !Array.isArray(data.phrases)) throw new Error('Invalid phrases data');
    var seen = {};
    var order = [];
    var byLang = {};
    data.phrases.forEach(function (e) {
      (byLang[e.lang] = byLang[e.lang] || []).push(e);
      if (!seen[e.id]) { seen[e.id] = true; order.push({ n: e.n, id: e.id, group: e.group }); }
    });
    var languages = {};
    Object.keys(data.languages).forEach(function (code) {
      var info = Object.assign({}, data.languages[code]);
      info.checked = (byLang[code] || []).length > 0 && byLang[code].every(function (e) { return e.checked === true; });
      languages[code] = info;
    });
    indexMeta({ version: data.version, languages: languages, groups: data.groups, phrases: order });
    addEntries(data.phrases);
  }

  function loadIndex() {
    if (window.location.protocol === 'file:' || !window.fetch) return loadScriptFallback().then(useFull);
    return fetchJson(DATA_DIR + 'index.json').then(indexMeta).catch(function () {
      return loadScriptFallback().then(useFull);
    });
  }

  /** Make sure the entries of these languages are there (unknown codes are skipped). */
  function loadLangs(codes) {
    var missing = codes.filter(function (code, i) {
      return code && codes.indexOf(code) === i && state.data.languages[code] && !state.loaded[code];
    });
    if (!missing.length) return Promise.resolve();
    return Promise.all(missing.map(function (code) {
      return fetchJson(DATA_DIR + code + '.json').then(function (file) {
        if (!file || !Array.isArray(file.phrases)) throw new Error('Invalid ' + code + '.json');
        addEntries(file.phrases);
      });
    })).catch(function () {
      return loadScriptFallback().then(useFull);
    });
  }

  function idsIn(groupId) {
    return state.order.filter(function (id) { return groupId === 'all' || state.groupOf[id] === groupId; });
  }

