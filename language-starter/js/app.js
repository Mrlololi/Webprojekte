  function params() {
    try {
      return new URLSearchParams(window.location.search);
    } catch (error) {
      return { get: function () { return null; }, has: function () { return false; } };
    }
  }

  function updateUrl() {
    if (!window.history || !window.history.replaceState) return;
    var query = [];
    if (state.from) query.push('from=' + state.from);
    if (state.to) query.push('to=' + state.to);
    query.push('ui=' + state.ui);
    try {
      window.history.replaceState(null, '', window.location.pathname + '?' + query.join('&') + window.location.hash);
    } catch (error) { /* file:// in some browsers */ }
  }

  function shareUrl() {
    return PAGE_URL + '?from=' + state.from + '&to=' + state.to + '&ui=' + state.ui;
  }

  function browserLang() {
    var list = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en']);
    for (var i = 0; i < list.length; i++) {
      var base = String(list[i]).toLowerCase().split('-')[0];
      if (base === 'nb' || base === 'nn') base = 'no';
      if (state.codes.indexOf(base) !== -1) return base;
    }
    return 'en';
  }

  function pickPair() {
    var p = params();
    var saved = store.get('pair', null) || {};
    var from = p.get('from');
    var to = p.get('to');
    var valid = function (code) { return code && state.codes.indexOf(code) !== -1; };
    state.from = valid(from) ? from : valid(saved.from) ? saved.from : browserLang();
    if (valid(to)) state.to = to;
    else if (!valid(from) && valid(saved.to)) state.to = saved.to;
    else state.to = '';
    if (state.to === state.from) state.to = '';
  }

  function setPair(from, to) {
    if (from === to) to = '';
    var changed = from !== state.from || to !== state.to;
    state.from = from;
    state.to = to;
    store.set('pair', { from: from, to: to });
    updateUrl();
    if (changed) {
      state.round = null;
      state.lastResult = null;
      loadPairProgress();
    }
    // A new language is one small file; draw when it is there.
    return loadLangs([from, to, 'en']).then(renderAll, showLoadError);
  }

  function showLoadError() {
    el.status.hidden = false;
    el.status.classList.add('is-error');
    el.status.setAttribute('data-i18n', 'error');
    el.status.textContent = t('error');
  }

