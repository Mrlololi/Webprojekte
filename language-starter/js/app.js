  /** Correct answer plus three others from the same topic, all with a different text. */
  function buildOptions(id, answerLang) {
    var correctText = flat(entry(answerLang, id));
    var used = [correctText];
    var picks = [];
    var sameGroup = shuffled(idsIn(state.groupOf[id]).filter(function (other) { return other !== id; }));
    var others = shuffled(state.order.filter(function (other) { return state.groupOf[other] !== state.groupOf[id]; }));
    sameGroup.concat(others).forEach(function (other) {
      if (picks.length >= OPTION_COUNT - 1) return;
      var text = flat(entry(answerLang, other));
      if (used.indexOf(text) !== -1) return;
      used.push(text);
      picks.push(other);
    });
    return shuffled(picks.concat(id));
  }

