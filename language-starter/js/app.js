  function pickUi() {
    var fromUrl = params().get('ui');
    if (fromUrl && I18N[fromUrl]) return fromUrl;
    var saved = store.get('ui', null);
    if (saved && uiReady(saved)) return saved;
    var nav = String(navigator.language || 'en').toLowerCase().split('-')[0];
    return uiReady(nav) ? nav : I18N.defaultLang;
  }

  function registerServiceWorker() {
    if (!('serviceWorker' in navigator)) return;
    var secure = window.location.protocol === 'https:' || window.location.hostname === 'localhost';
    if (!secure) return;
    window.addEventListener('load', function () {
      navigator.serviceWorker.register('sw.js').catch(function () { /* offline mode is a bonus */ });
    });
  }

  function boot() {
    // ?review (picker) or ?review=fi: the review page for native speakers.
    var query = params();
    if (query.has('review')) {
      bootReview(String(query.get('review') || '').toLowerCase().trim());
      return;
    }

    state.ui = pickUi();
    applyStaticStrings();
    document.documentElement.classList.remove('i18n-pending');
    el.storageNotice.hidden = store.available;
    var savedQuiz = store.get('quiz', null);
    if (savedQuiz && typeof savedQuiz === 'object') {
      if (savedQuiz.dir === 'say' || savedQuiz.dir === 'learn') state.quiz.dir = savedQuiz.dir;
      if (typeof savedQuiz.group === 'string') state.quiz.group = savedQuiz.group;
    }
    var savedGroup = store.get('group', null);
    if (typeof savedGroup === 'string') state.group = savedGroup;
    wire();
    registerServiceWorker();
    // iOS may offer voices only after the first tap: redraw the Listen buttons when they arrive.
    voice.onChange(function () { if (state.data && state.to) renderCards(); });

    Promise.all([loadIndex(), voice.init()])
      .then(function () {
        if (groupIds().indexOf(state.group) === -1) state.group = groupIds()[0];
        if (state.quiz.group !== 'all' && groupIds().indexOf(state.quiz.group) === -1) state.quiz.group = 'all';
        pickPair();
        store.set('pair', { from: state.from, to: state.to });
        updateUrl();
        loadPairProgress();
        return loadLangs([state.from, state.to, 'en']);
      })
      .then(function () {
        el.status.hidden = true;
        renderAll();
      })
      .catch(showLoadError);
  }

  boot();
