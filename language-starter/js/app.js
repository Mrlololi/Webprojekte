  function answer(chosen) {
    var round = state.round;
    if (!round || round.answered) return;
    var id = currentId();
    var isCorrect = chosen === id;
    round.answered = true;
    round.lastChosen = chosen;
    if (isCorrect) round.correct += 1;
    else round.wrong.push(id);
    recordAnswer(id, isCorrect);
    saveRound();
    state.answeredAt = Date.now();
    markOptions(chosen, id);
    renderFeedback(isCorrect, id);
    renderQuestionTexts();
    el.nextBtn.hidden = false;
    el.nextBtn.focus();
  }

