  function span(className, text, lang) {
    var node = document.createElement('span');
    if (className) node.className = className;
    if (text !== undefined && text !== null) node.textContent = text;
    if (lang) node.lang = lang;
    return node;
  }

  function make(tag, className, text) {
    var node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined && text !== null) node.textContent = text;
    return node;
  }

  function shuffled(list) {
    var copy = list.slice();
    for (var i = copy.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1));
      var tmp = copy[i];
      copy[i] = copy[j];
      copy[j] = tmp;
    }
    return copy;
  }

  function svgIcon(kind) {
    var ns = 'http://www.w3.org/2000/svg';
    var paths = {
      ok: 'm5 12.5 4.5 4.5L19 7.5',
      bad: 'm6.5 6.5 11 11M17.5 6.5l-11 11',
      sound: 'M4 9.5h3.5L12 5.5v13l-4.5-4H4zM15.5 8.5a5 5 0 0 1 0 7M18.5 5.5a9 9 0 0 1 0 13'
    };
    var svg = document.createElementNS(ns, 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('focusable', 'false');
    var path = document.createElementNS(ns, 'path');
    path.setAttribute('d', paths[kind]);
    svg.appendChild(path);
    return svg;
  }

  function reducedMotion() {
    return Boolean(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches);
  }

  /** Text with {X} -> text nodes and a visible "…" gap. */
  function fillText(node, text) {
    var parts = String(text).split('{X}');
    var children = [];
    parts.forEach(function (part, index) {
      if (index > 0) {
        var gap = span('gap', GAP);
        gap.title = t('card.gap');
        children.push(gap);
      }
      if (part) children.push(document.createTextNode(part));
    });
    node.replaceChildren.apply(node, children);
    return node;
  }

  function plain(text) {
    return String(text).split('{X}').join(GAP);
  }

  function entry(lang, id) {
    return state.byLang[lang] && state.byLang[lang][id];
  }

  /** One line for an entry: the text, or both forms "m / f". */
  function flat(e) {
    if (!e) return '';
    return e.forms ? plain(e.forms.m) + ' / ' + plain(e.forms.f) : plain(e.text);
  }

  function flatTranslit(e) {
    if (!e || !e.translit) return '';
    return typeof e.translit === 'object' ? plain(e.translit.m) + ' / ' + plain(e.translit.f) : plain(e.translit);
  }

  function langData(code) {
    return state.data.languages[code];
  }

  // Language names are looked up once per interface language: sorting 42 names asks for
  // them hundreds of times, and Intl.DisplayNames is slow to create.
  var nameCache = {};

  function langName(code) {
    var key = state.ui + ':' + code;
    if (nameCache[key]) return nameCache[key];
    var info = langData(code);
    var result = info ? info.endonym : code;
    try {
      var names = nameCache[state.ui] || (nameCache[state.ui] = new Intl.DisplayNames([uiInfo(state.ui).locale], { type: 'language' }));
      var name = names.of(code === 'no' ? 'nb' : code);
      if (name && name !== code && name !== 'nb') result = name;
    } catch (error) { /* no Intl.DisplayNames */ }
    nameCache[key] = result;
    return result;
  }

  /** "ქართული (Georgisch)", or just the endonym when both are the same. */
  function langLabel(code) {
    var endonym = langData(code).endonym;
    var name = langName(code);
    return name.toLowerCase() === endonym.toLowerCase() ? endonym : endonym + ' (' + name + ')';
  }

  function sortedCodes() {
    var collator;
    try { collator = new Intl.Collator(uiInfo(state.ui).locale); } catch (error) { collator = null; }
    return state.codes.slice().sort(function (a, b) {
      var x = langName(a);
      var y = langName(b);
      return collator ? collator.compare(x, y) : (x < y ? -1 : 1);
    });
  }

  function groupName(groupId) {
    var group = state.data.groups.filter(function (g) { return g.id === groupId; })[0];
    if (!group) return groupId;
    return group[state.ui] || group.en;
  }

