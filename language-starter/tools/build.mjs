// Language Starter build step. Run after every change to data/phrases.json:
//
//   node tools/build.mjs
//
// 1. data/phrases.js: the same data as phrases.json, for opening the page
//    from disk (file://), where browsers block fetch().
// 2. The static English -> German phrase list in index.html (between the
//    "static:start" and "static:end" comments), so the page is readable
//    without JavaScript.
// 3. Checks the data and stops with an error if something is wrong.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(root, 'data', 'phrases.json'), 'utf8'));

/* ---------- checks ---------- */

const errors = [];
const ids = [...new Set(data.phrases.map((p) => p.id))];
const byLang = {};
for (const p of data.phrases) (byLang[p.lang] ||= {})[p.id] = p;
const isText = (v) => typeof v === 'string' && v.trim().length > 0;

for (const lang of Object.keys(data.languages)) {
  for (const id of ids) {
    const p = byLang[lang]?.[id];
    if (!p) { errors.push(`${lang}: ${id} missing`); continue; }
    if (p.forms ? !(isText(p.forms.m) && isText(p.forms.f) && p.text === null) : !isText(p.text)) errors.push(`${lang} ${id}: needs text or forms {m, f}`);
    const all = [p.text, p.forms?.m, p.forms?.f].filter(Boolean).join(' ');
    if (/[—–]/.test(all)) errors.push(`${lang} ${id}: long dash`);
    if (/\p{Extended_Pictographic}/u.test(all)) errors.push(`${lang} ${id}: emoji`);
  }
}
const ns = new Map();
for (const p of data.phrases) {
  if (ns.has(p.id) && ns.get(p.id) !== p.n) errors.push(`${p.id}: n differs between languages`);
  ns.set(p.id, p.n);
}
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

/* ---------- 1. phrases.js ---------- */

writeFileSync(
  join(root, 'data', 'phrases.js'),
  '/* Generated copy of phrases.json for file:// use. Do not edit - edit phrases.json and run node tools/build.mjs. */\n' +
  'window.LS_PHRASES = ' + JSON.stringify(data) + ';\n'
);

/* ---------- 1b. one small file per language (the app loads only what it needs) ---------- */

// data/index.json: languages (with "checked" when every entry is checked), groups and the
// phrase order. data/xx.json: the entries of one language. A reviewer on a phone downloads
// the index and two languages instead of all 42.
const languages = {};
for (const [code, info] of Object.entries(data.languages)) {
  languages[code] = { ...info, checked: ids.every((id) => byLang[code][id].checked === true) };
}
const order = [...ids].sort((a, b) => ns.get(a) - ns.get(b)).map((id) => ({ n: ns.get(id), id, group: byLang.en[id].group }));
const generated = 'Generated from phrases.json by tools/build.mjs. Do not edit.';
writeFileSync(join(root, 'data', 'index.json'), JSON.stringify({ version: data.version, generated, languages, groups: data.groups, phrases: order }) + '\n');
for (const code of Object.keys(data.languages)) {
  writeFileSync(join(root, 'data', `${code}.json`), JSON.stringify({ lang: code, generated, phrases: data.phrases.filter((p) => p.lang === code) }) + '\n');
}

/* ---------- 2. static EN -> DE list ---------- */

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const show = (p) => esc(p.forms ? `m: ${p.forms.m} / f: ${p.forms.f}` : p.text).replace(/\{X\}/g, '…');
const ordered = [...ids].sort((a, b) => ns.get(a) - ns.get(b));

let html = '\n    <section class="container static-fallback" aria-labelledby="static-title">\n';
html += '      <h2 id="static-title">English to German: all 45 phrases</h2>\n';
html += '      <p class="section-text">This list works without JavaScript. With JavaScript you can pick any of the 42 languages, listen, play the quiz and print a phrase card.</p>\n';
for (const group of data.groups) {
  html += `      <h3>${esc(group.en)}</h3>\n      <table>\n        <thead><tr><th scope="col">Nr.</th><th scope="col">English</th><th scope="col" lang="de">Deutsch</th></tr></thead>\n        <tbody>\n`;
  for (const id of ordered.filter((i) => byLang.en[i].group === group.id)) {
    html += `          <tr><td>${ns.get(id)}</td><td lang="en">${show(byLang.en[id])}</td><td lang="de">${show(byLang.de[id])}</td></tr>\n`;
  }
  html += '        </tbody>\n      </table>\n';
}
html += '    </section>\n    ';

const indexPath = join(root, 'index.html');
const index = readFileSync(indexPath, 'utf8');
const start = '<!-- static:start (generated by tools/build.mjs from data/phrases.json - do not edit by hand) -->';
const end = '<!-- static:end -->';
const a = index.indexOf(start);
const b = index.indexOf(end);
if (a === -1 || b === -1) throw new Error('static markers not found in index.html');
writeFileSync(indexPath, index.slice(0, a + start.length) + html + index.slice(b));

console.log(`ok: ${Object.keys(data.languages).length} languages, ${ids.length} phrases, ${data.phrases.length} entries`);
